#!/usr/bin/env python3
"""Generate tests/fixtures/pretty_repr.golden from Python Rich.

Runs `rich.pretty.pretty_repr` on a fixed set of Python values (lists,
tuples, dicts, sets, strings) at several widths and option settings and
records the output. `tests/pretty_parity.rs` builds the same values in Rust
(Vec, tuples, BTreeMap/HashMap, BTreeSet, &str), runs fast-rich's
`pretty_repr` and compares.

Usage (needs `rich` importable, e.g. `pip install rich==15.0.0`):

    python3 scripts/gen_pretty_golden.py > tests/fixtures/pretty_repr.golden

Format (one record per line):

    C <value-id> <max_width> <indent_size> <max_length> <max_string> <max_depth> <expand_all>
    E <hex>              expected output (UTF-8 hex, `-` = empty)

Options that are None are written as `-`; expand_all is 0 or 1.

Python quotes strings with ' and Rust with ", so the Rust test replaces '
with " in the expected output. The values are chosen so that this is the
only difference between Python's repr and Rust's Debug: strings contain no
quotes or backslashes, there are no booleans or None, sets hold small
non-negative ints (which Python iterates in sorted order) and are never
empty (Python writes `set()`, Rust `{}`), and dicts are built with sorted
keys so their order matches BTreeMap.
"""

from importlib.metadata import version

from rich.pretty import pretty_repr

# Keep in sync with `value()` in tests/pretty_parity.rs.
VALUES = {
    "empty_list": [],
    "empty_dict": {},
    "empty_tuple": (),
    "nested_empty": [[], [[]]],
    "empties_tuple": ([], {}, ()),
    "ints": list(range(12)),
    "negatives": [-1, -20, 300, 4000],
    "floats": [1.5, -2.25, 0.0, 100.125],
    "tuple1": (1,),
    "tuple1_nested": ([1, 2, 3],),
    "tuple_of_tuple1": ((1,), (2,)),
    "tuple_mixed": (1, "two", [3, 4], {"five": 5}),
    "strings": ["alpha", "beta", "gamma", "delta", "epsilon"],
    "unicode": ["é日本🎉", "naïve", "x"],
    "brackets": ["[a]", "{b}", "(c)", "d, e: f", "]"],
    "dict": {"apple": [1, 2], "banana": [3, 4, 5], "cherry": []},
    "dict_nested": {"outer": {"inner": {"deep": [1, 2, 3]}}},
    "dict_tuple_keys": {(1, 2): "a", (3, 4): "b"},
    "dict_one": {"key": [10, 20, 30]},
    "set": {1, 2, 3, 5, 8, 13},
    "list_of_sets": [{1, 2}, {3}],
    "matrix": [[1, 2, 3], [4, 5, 6], [7, 8, 9]],
    "records": [("alice", [1, 2]), ("bob", [3])],
    "long_strings": [
        "Lorem ipsum dolor sit amet",
        "consectetur adipiscing elit",
        "sed do eiusmod tempor",
    ],
    "string": "hello world",
    "deep": [[[[[[1]]]]]],
}

WIDTHS = [0, 1, 4, 8, 12, 16, 20, 30, 50, 80]

SETTINGS = [dict(max_width=w) for w in WIDTHS] + [
    dict(max_width=20, indent_size=2),
    dict(max_width=10, indent_size=1),
    dict(max_width=80, max_length=0),
    dict(max_width=80, max_length=1),
    dict(max_width=12, max_length=2),
    dict(max_width=80, max_string=0),
    dict(max_width=80, max_string=3),
    dict(max_width=12, max_string=5),
    dict(max_width=80, max_depth=0),
    dict(max_width=80, max_depth=1),
    dict(max_width=10, max_depth=2),
    dict(max_width=80, expand_all=True),
    dict(max_width=10, max_length=2, max_string=2, max_depth=2),
]


def opt(value):
    return "-" if value is None else str(value)


def to_hex(s):
    return s.encode("utf-8").hex() or "-"


def main():
    print(f"# Generated by scripts/gen_pretty_golden.py from rich {version('rich')}")
    for name, value in VALUES.items():
        if isinstance(value, set):
            assert list(value) == sorted(value), "set order must be sorted"
        for setting in SETTINGS:
            options = dict(
                max_width=80,
                indent_size=4,
                max_length=None,
                max_string=None,
                max_depth=None,
                expand_all=False,
            )
            options.update(setting)
            out = pretty_repr(value, **options)
            print(
                "C",
                name,
                options["max_width"],
                options["indent_size"],
                opt(options["max_length"]),
                opt(options["max_string"]),
                opt(options["max_depth"]),
                int(options["expand_all"]),
            )
            print("E", to_hex(out))


if __name__ == "__main__":
    main()
