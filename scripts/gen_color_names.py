#!/usr/bin/env python3
"""Generate fast-rich's table of Rich's named 256-palette colors.

Writes two files from `rich.color.ANSI_COLOR_NAMES` (235 names such as
`grey23` or `dark_orange3`, each mapped to a palette index):

- `src/color_names.rs`: the table `Color::parse` looks names up in, sorted
  by name for binary search.
- `tests/fixtures/color_names.golden`: `<name> <index>` per line, in Rich's
  order, checked by `tests/theme_parity.rs`.

Usage (needs `rich` importable, e.g. `pip install rich==15.0.0`, or
`PYTHONPATH` pointed at an unzipped rich wheel):

    python3 scripts/gen_color_names.py
"""

from importlib.metadata import version
from pathlib import Path

from rich.color import ANSI_COLOR_NAMES

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    rich_version = version("rich")
    names = sorted(ANSI_COLOR_NAMES.items())

    rust = [
        f"// @generated by scripts/gen_color_names.py from rich {rich_version}"
        " (rich.color.ANSI_COLOR_NAMES).",
        "// Do not edit by hand.",
        "",
        "/// Rich's named 256-palette colors (`grey23`, `dark_orange3`, ...),",
        "/// sorted by name for binary search. Each name maps to a palette index.",
        "pub(crate) const ANSI_COLOR_NAMES: &[(&str, u8)] = &[",
    ]
    rust += [f'    ("{name}", {index}),' for name, index in names]
    rust += ["];", ""]
    (ROOT / "src" / "color_names.rs").write_text("\n".join(rust))

    golden = [f"# rich {rich_version}: rich.color.ANSI_COLOR_NAMES (<name> <index>)"]
    golden += [f"{name} {index}" for name, index in ANSI_COLOR_NAMES.items()]
    (ROOT / "tests" / "fixtures" / "color_names.golden").write_text(
        "\n".join(golden) + "\n"
    )


if __name__ == "__main__":
    main()
