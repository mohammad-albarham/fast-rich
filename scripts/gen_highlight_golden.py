def random_cases(n, seed=20261118):
    rng = random.Random(seed)
    for _ in range(n):
        yield "".join(rng.choice(TOKENS) for _ in range(rng.randint(1, 14))), False


def describe(style):
    color = ""
    if style.color is not None and not style.color.is_default:
        color = style.color.name
    flags = "".join(
        flag
        for flag, on in (
            ("b", style.bold),
            ("d", style.dim),
            ("i", style.italic),
            ("u", style.underline),
        )
        if on
    )
    return f"{color}:{flags}" if color or flags else ""


def runs(console, text):
    out = []
    plain = text.plain
    for i in range(len(plain)):
        desc = describe(text.get_style_at_offset(console, i))
        if out and out[-1][2] == desc and out[-1][1] == i:
            out[-1][1] = i + 1
        else:
            out.append([i, i + 1, desc])
    return [r for r in out if r[2]]


def main():
    console = Console(color_system="truecolor", force_terminal=True)
    print(f"# Generated by scripts/gen_highlight_golden.py from rich {version('rich')}")
    print("# I <utf8-hex> <m=markup|p=plain>; R <char-start> <char-end> <color:flags>")
    for text, markup in CASES + list(random_cases(800)):
        rendered = console.render_str(text, markup=markup, emoji=False, highlight=True)
        print("# " + text.encode("unicode_escape").decode("ascii"))
        print(f"I {text.encode('utf-8').hex() or '-'} {'m' if markup else 'p'}")
        for start, end, desc in runs(console, rendered):
            print(f"R {start} {end} {desc}")


if __name__ == "__main__":
    main()
