#!/usr/bin/env python3
"""Generate fast-rich's copy of Rich's default theme styles.

Writes two files from `rich.default_styles.DEFAULT_STYLES` (154 named
styles such as `table.header` or `bar.complete`):

- `src/default_styles.rs`: `(name, style string)` pairs in Rich's order.
  The style strings are Rich's own (`str(style)`), parsed at first use by
  `Style::parse`.
- `tests/fixtures/default_styles.golden`: what each style resolves to in
  Rich, checked by `tests/theme_parity.rs`.

Golden format (one record per line, space-separated):

    <name> <color> <bgcolor> <bold> <dim> <italic> <underline> <blink> <blink2> <reverse> <conceal> <strike> <underline2> <frame> <encircle> <overline>

- color / bgcolor: `-` (unset), `default`, `n<index>` (standard or 256
  palette) or `#rrggbb` (truecolor).
- flags: `1` (on), `0` (explicitly off, Rich's `not bold`), `-` (unset),
  for all 13 of Rich's attributes in Rich's bit order.

Usage (needs `rich` importable, e.g. `pip install rich==15.0.0`, or
`PYTHONPATH` pointed at an unzipped rich wheel):

    python3 scripts/gen_default_styles.py
"""

from importlib.metadata import version
from pathlib import Path

from rich.color import ColorType
from rich.default_styles import DEFAULT_STYLES

ROOT = Path(__file__).resolve().parent.parent

# Rich's attribute bits (rich.style.Style._attributes), in golden order.
ATTRIBUTES = [
    ("bold", 1),
    ("dim", 2),
    ("italic", 4),
    ("underline", 8),
    ("blink", 16),
    ("blink2", 32),
    ("reverse", 64),
    ("conceal", 128),
    ("strike", 256),
    ("underline2", 512),
    ("frame", 1024),
    ("encircle", 2048),
    ("overline", 4096),
]


def color_field(color) -> str:
    if color is None:
        return "-"
    if color.type == ColorType.DEFAULT:
        return "default"
    if color.type in (ColorType.STANDARD, ColorType.EIGHT_BIT):
        return f"n{color.number}"
    r, g, b = color.triplet
    return f"#{r:02x}{g:02x}{b:02x}"


def flag_field(style, bit: int) -> str:
    if not style._set_attributes & bit:
        return "-"
    return "1" if style._attributes & bit else "0"


def main() -> None:
    rich_version = version("rich")

    rust = [
        f"// @generated by scripts/gen_default_styles.py from rich {rich_version}"
        " (rich.default_styles.DEFAULT_STYLES).",
        "// Do not edit by hand.",
        "",
        "/// Rich's default theme: `(name, style string)` in Rich's order. The",
        "/// strings are Rich's own and are parsed with `Style::parse`.",
        "pub(crate) const DEFAULT_STYLES: &[(&str, &str)] = &[",
    ]
    golden = [
        f"# rich {rich_version}: rich.default_styles.DEFAULT_STYLES",
        "# <name> <color> <bgcolor> "
        + " ".join(f"<{attr}>" for attr, _ in ATTRIBUTES),
    ]
    for name, style in DEFAULT_STYLES.items():
        rust.append(f'    ("{name}", "{style}"),')
        flags = [flag_field(style, bit) for _, bit in ATTRIBUTES]
        golden.append(
            " ".join(
                [name, color_field(style.color), color_field(style.bgcolor)]
                + flags
            )
        )
    rust += ["];", ""]

    (ROOT / "src" / "default_styles.rs").write_text("\n".join(rust))
    (ROOT / "tests" / "fixtures" / "default_styles.golden").write_text(
        "\n".join(golden) + "\n"
    )


if __name__ == "__main__":
    main()
